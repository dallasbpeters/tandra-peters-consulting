import { CheckmarkCircleIcon } from "@sanity/icons";
import { defineField, defineType } from "sanity";

const kindOptions = [
  { title: "Work task", value: "task" },
  { title: "Content calendar entry", value: "content" },
] as const;

const originOptions = [
  { title: "Seed (from the desk playbook)", value: "seed" },
  { title: "Generated (from the desk AI)", value: "generated" },
  { title: "Added by hand", value: "manual" },
] as const;

const statusOptions = [
  { title: "To do", value: "todo" },
  { title: "Done", value: "done" },
  { title: "Idea", value: "idea" },
  { title: "Scheduled", value: "scheduled" },
  { title: "Published", value: "published" },
] as const;

const buyerStageOptions = [
  { title: "Awareness", value: "awareness" },
  { title: "Consideration", value: "consideration" },
  { title: "Decision", value: "decision" },
  { title: "Retention", value: "retention" },
] as const;

/**
 * A single item on Tandra's Desk board — either a work task (with a To do / Done
 * status) or a content-calendar entry (with a pillar, buyer stage, and publish
 * date). Written by `/api/desk-board` and generated by `/api/desk-plan`, stored
 * as drafts so they stay out of public-read content.
 */
export const deskBoardItemType = defineType({
  name: "deskBoardItem",
  title: "Desk board item",
  type: "document",
  icon: CheckmarkCircleIcon,
  fields: [
    defineField({
      name: "kind",
      title: "Kind",
      type: "string",
      initialValue: "task",
      options: { layout: "radio", list: kindOptions },
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: "title",
      title: "Title",
      type: "string",
      validation: (Rule) => Rule.required().max(200),
    }),
    defineField({
      name: "detail",
      title: "Detail",
      type: "text",
      rows: 3,
      description:
        "Task: the outcome it produces. Content: the angle or promise of the piece.",
    }),
    defineField({
      name: "channel",
      title: "Channel or content type",
      type: "string",
      description:
        "Task: where the work happens (direct mail, video, partner email). Content: searchable, shareable, or both.",
    }),
    defineField({
      name: "href",
      title: "Deep link",
      type: "string",
      description: "Optional in-app path this item opens, e.g. /ads.",
    }),
    defineField({
      name: "status",
      title: "Status",
      type: "string",
      initialValue: "todo",
      options: { layout: "radio", list: statusOptions },
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: "origin",
      title: "Origin",
      type: "string",
      initialValue: "manual",
      options: { layout: "radio", list: originOptions },
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: "seedKey",
      title: "Seed key",
      type: "string",
      readOnly: true,
      description:
        "Stable key that links a status back to a hard-coded seed card on the Desk page.",
    }),
    defineField({
      name: "pillar",
      title: "Content pillar",
      type: "string",
      hidden: ({ parent }) => parent?.kind !== "content",
      description: "The topic cluster this content belongs to.",
    }),
    defineField({
      name: "buyerStage",
      title: "Buyer stage",
      type: "string",
      options: { layout: "radio", list: buyerStageOptions },
      hidden: ({ parent }) => parent?.kind !== "content",
    }),
    defineField({
      name: "publishDate",
      title: "Publish date",
      type: "date",
      hidden: ({ parent }) => parent?.kind !== "content",
    }),
    defineField({
      name: "createdBy",
      title: "Created by",
      type: "string",
      readOnly: true,
    }),
    defineField({
      name: "createdAt",
      title: "Created at",
      type: "datetime",
      readOnly: true,
    }),
    defineField({
      name: "completedAt",
      title: "Completed at",
      type: "datetime",
      readOnly: true,
    }),
  ],
  preview: {
    select: {
      title: "title",
      kind: "kind",
      status: "status",
      publishDate: "publishDate",
    },
    prepare({ title, kind, status, publishDate }) {
      const kindLabel = kind === "content" ? "Content" : "Task";
      const suffix = publishDate ? ` · ${publishDate}` : "";
      return {
        title: title ?? "Untitled board item",
        subtitle: `${kindLabel} · ${status ?? "todo"}${suffix}`,
      };
    },
  },
});
